async function addStudents() {
  try {
    console.log('='.repeat(60));
    console.log('📚 Adding 2024 Batch Students to Database');
    console.log('='.repeat(60));

    // Parse raw data
    const lines = rawData.split('\n').filter(line => line.trim());
    const students = [];
    const processedRegNos = new Set();

    for (const line of lines) {
      // Split by tab or multiple spaces
      const parts = line.trim().split(/\s+/);
      
      if (parts.length < 2) continue;

      const rawRegNo = parts[0];
      
      // Extract name (everything between reg_no and last part if last part is date, or everything else)
      // Check if last part is a date (contains - or /)
      let nameParts = [];
      let dob = null;
      
      const lastPart = parts[parts.length - 1];
      const isDate = /[\d]{1,2}[-/][\d]{1,2}[-/][\d]{2,4}/.test(lastPart);
      
      if (isDate) {
        dob = lastPart;
        nameParts = parts.slice(1, parts.length - 1);
      } else {
        nameParts = parts.slice(1);
      }
      
      const name = nameParts.join(' ');
      
      // Transform reg_no: 732224CS001 -> 24cs001
      // Remove first 4 chars (7322) and lowercase
      const regNo = rawRegNo.slice(4).toLowerCase();

      if (processedRegNos.has(regNo)) {
        console.log(`⚠️  Duplicate reg_no found in input: ${regNo} (${name}), skipping...`);
        continue;
      }
      
      processedRegNos.add(regNo);
      
      students.push({
        reg_no: regNo,
        name: name,
        dob: dob
      });
    }

    console.log(`Total unique students to process: ${students.length}\n`);

    let created = 0;
    let updated = 0;
    let skipped = 0;
    const errors = [];

    for (const student of students) {
      try {
        // Generate email: reg_no + @nandhaengg.org
        const email = `${student.reg_no}@nandhaengg.org`;
        
        // Password is the reg_no itself
        const password = student.reg_no;

        // Check if user already exists by email or reg_no
        const existingUser = await prisma.user.findFirst({
          where: {
            OR: [
              { email: email },
              { reg_no: student.reg_no }
            ]
          }
        });

        if (existingUser) {
          // Update existing user
          console.log(`🔄 Updating existing student: ${student.reg_no} (${email})`);
          
          // Hash password
          const hashedPassword = await bcrypt.hash(password, SALT_ROUNDS);
          
          await prisma.user.update({
            where: { id: existingUser.id },
            data: {
              reg_no: student.reg_no,
              email: email,
              name: student.name,
              password: hashedPassword,
              role: 'STUDENT',
            }
          });
          
          updated++;
        } else {
          // Create new user
          console.log(`➕ Creating new student: ${student.reg_no} (${email})`);
          
          // Hash password
          const hashedPassword = await bcrypt.hash(password, SALT_ROUNDS);
          
          await prisma.user.create({
            data: {
              reg_no: student.reg_no,
              email: email,
              name: student.name,
              password: hashedPassword,
              role: 'STUDENT',
            }
          });
          
          created++;
        }
      } catch (error) {
        const errorMsg = `Error processing ${student.reg_no}: ${error.message}`;
        console.error(`❌ ${errorMsg}`);
        errors.push({ reg_no: student.reg_no, error: error.message });
        skipped++;
      }
    }

    console.log('\n' + '='.repeat(60));
    console.log('📊 Summary');
    console.log('='.repeat(60));
    console.log(`✅ Created: ${created}`);
    console.log(`🔄 Updated: ${updated}`);
    console.log(`❌ Errors: ${skipped}`);
    console.log('='.repeat(60) + '\n');

    if (errors.length > 0) {
      console.log('❌ Errors encountered:');
      errors.forEach(({ reg_no, error }) => {
        console.log(`   ${reg_no}: ${error}`);
      });
      console.log('');
    }

    console.log('✅ Student import completed!\n');
    console.log('📝 Login Information:');
    console.log('   Email format: <reg_id>@nandhaengg.org (e.g., 24cs001@nandhaengg.org)');
    console.log('   Password: <reg_id> (e.g., 24cs001)');
    console.log('   Students can also login with Google using the same email address\n');

  } catch (error) {
    console.error('\n❌ Fatal error:');
    if (error.code === 'P1001') {
      console.error('   Database connection failed. Check your DATABASE_URL in .env');
    } else {
      console.error('   ' + error.message);
    }
    console.error('\n');
    process.exit(1);
  } finally {
    await prisma.$disconnect();
  }
}

addStudents();
